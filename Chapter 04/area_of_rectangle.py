# rectangle_area.py
# A simple program to calculate the area of a rectangle

# --- Define Variables ---
# Assign values for the length and width of the rectangle
# Note: We are using floating-point numbers (float) here
length = 10.5
width = 4.0

# --- Perform Calculation ---
# Calculate the area using the multiplication operator
area = length * width

# --- Display the Result ---
# Create a descriptive message (string)
output_message = "The area of the rectangle is: "

# Print the message and the calculated area
# The print function can display multiple items separated by commas
print(output_message, area)

# You can also print the result directly
print("Rectangle Length:", length)
print("Rectangle Width:", width)
print("Calculated Area:", area)